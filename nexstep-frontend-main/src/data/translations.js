// Earlier content imports were saved as UTF-8 bytes interpreted as Latin-1.
// Normalise that legacy data once so every existing `translations[lang]` user
// receives real Urdu characters rather than mojibake.
export function repairUrduText(value) {
  if (typeof value !== 'string') return value;
  try {
    return decodeURIComponent(escape(value));
  } catch {
    return value;
  }
}

function repairUrduResource(value) {
  if (typeof value === 'string') return repairUrduText(value);
  if (Array.isArray(value)) return value.map(repairUrduResource);
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, entry]) => [key, repairUrduResource(entry)]));
  }
  return value;
}

translations.ur = repairUrduResource(translations.ur);
